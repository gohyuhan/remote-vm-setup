#!/usr/bin/env bash
# Snapshot this Mac's configs and installed versions into ./config. Run on the source Mac after
# changing a config or upgrading a tool; setup.sh then installs exactly these versions.
# Only config is copied: no sessions, logs, caches, plugin clones, or credentials.
set -euo pipefail

repo="$(cd "$(dirname "$0")" && pwd)"
out="$repo/config"
lock="$out/versions.lock"
app_support="$HOME/Library/Application Support"

rm -rf "$out"
mkdir -p "$out/nvim" "$out/gitti" "$out/koshi" "$out/claude/skills"

# nvim: plugins, Mason tools, and state live in ~/.local/share/nvim and are rebuilt by setup.sh.
cp -R "$HOME/.config/nvim/init.lua" "$HOME/.config/nvim/lua" "$HOME/.config/nvim/.stylua.toml" "$out/nvim/"

# lazy-lock.json from the commits the plugins are checked out at, since that is what runs here
# even when the file lags behind (e.g. after a manual rollback). Same format lazy.nvim writes
# (lua/lazy/manage/lock.lua), so lazy rewrites it byte-for-byte on the target.
python3 - "$HOME" "$out/nvim/lazy-lock.json" <<'PY'
import json, os, subprocess, sys

home, target = sys.argv[1], sys.argv[2]
plugins = json.load(open(home + "/.config/nvim/lazy-lock.json"))
for name, info in plugins.items():
    plugin_dir = home + "/.local/share/nvim/lazy/" + name
    if not os.path.isdir(plugin_dir):
        continue
    head = subprocess.run(["git", "-C", plugin_dir, "rev-parse", "HEAD"],
                          capture_output=True, text=True, check=True).stdout.strip()
    if head != info["commit"]:
        print("lazy-lock.json: %s is checked out at %s, the file says %s" % (name, head[:7], info["commit"][:7]))
        info["commit"] = head
entries = ['  "%s": { "branch": "%s", "commit": "%s" }' % (name, plugins[name]["branch"], plugins[name]["commit"])
           for name in sorted(plugins)]
open(target, "w").write("{\n" + ",\n".join(entries) + "\n}\n")
PY

cp "$app_support/gitti/config.json" "$out/gitti/"

# koshi: skip logs/, remote/ (TLS pins and tokens), and update.json (update state).
cp -R "$app_support/koshi/koshi.kdl" "$app_support/koshi/keybinding.kdl" \
  "$app_support/koshi/themes" "$app_support/koshi/profile" "$out/koshi/"

cp "$HOME/.claude/RTK.md" "$out/claude/"

# graphify is not part of this setup. CLAUDE.md's "13. SKILLS" section only names it, so drop
# that section (up to the next --- rule).
awk '/^## 13\. SKILLS$/ {skip = 1} /^---$/ {skip = 0} !skip' "$HOME/.claude/CLAUDE.md" >"$out/claude/CLAUDE.md"

# settings.json: swap this Mac's $HOME for __HOME__ (setup.sh puts the target's back), and drop
# the hooks that call graphify.
python3 - "$HOME" "$out/claude/settings.json" <<'PY'
import json, sys

home, target = sys.argv[1], sys.argv[2]
settings = json.loads(open(home + "/.claude/settings.json").read().replace(home, "__HOME__"))
hooks = settings.get("hooks", {})
for event in hooks:
    kept = []
    for group in hooks[event]:
        group["hooks"] = [hook for hook in group["hooks"] if "graphify" not in hook["command"]]
        if group["hooks"]:
            kept.append(group)
    hooks[event] = kept
open(target, "w").write(json.dumps(settings, indent=2) + "\n")
PY

if grep -qi graphify "$out/claude/CLAUDE.md" "$out/claude/settings.json"; then
  echo "ERROR: graphify is still referenced in the CLAUDE.md or settings.json snapshot." >&2
  exit 1
fi

# The glob skips .trash/. synced/ holds skills that claude.ai syncs on its own.
for skill in "$HOME"/.claude/skills/*/; do
  skill="${skill%/}"
  case "$(basename "$skill")" in
    synced | graphify) continue ;;
  esac
  cp -R "$skill" "$out/claude/skills/"
done

find "$out" -name .DS_Store -delete

# version_of COMMAND...: the first x.y[.z] number in the command's first output line, or nothing
# if the command fails (an error such as "GLIBC_2.38 not found" holds a number too).
version_of() {
  local output
  output="$("$@" 2>&1)" || return 1
  printf '%s\n' "$output" | sed -n 1p | grep -oE '[0-9]+\.[0-9]+(\.[0-9]+)?' | sed -n 1p
}

{
  echo "# Generated by collect.sh. Format: <kind> <name> <version...>"
  echo "tool neovim $(version_of nvim --version)"
  echo "tool go $(version_of go version)"
  echo "tool node $(version_of node --version)"
  echo "tool python $(version_of python3 --version)"
  echo "tool rust $(version_of rustc --version)"
  echo "tool ripgrep $(version_of rg --version)"
  echo "tool fd $(version_of fd --version)"
  echo "tool tree-sitter-cli $(version_of tree-sitter --version)"
  echo "tool gopls $(version_of gopls version)"
  echo "tool uv $(version_of uv --version)"
  echo "tool rtk $(version_of rtk --version)"
  echo "tool gitti $(version_of gitti --version)"
  echo "tool koshi $(version_of koshi --version)"
  echo "tool claude-code $(version_of claude --version)"
  echo "tool pre-commit $(version_of pre-commit --version)"
} >"$lock"

python3 - "$HOME" >>"$lock" <<'PY'
import glob, json, os, re, subprocess, sys

home = sys.argv[1]

# Mason: the version each package was installed at, from its receipt's package URL, and the
# registry version that installed it (package definitions change between registry versions).
for receipt in sorted(glob.glob(home + "/.local/share/nvim/mason/packages/*/mason-receipt.json")):
    data = json.load(open(receipt))
    registry = data["registry"]
    print("mason", data["name"], data["source"]["id"].rsplit("@", 1)[1],
          "%s:%s/%s@%s" % (registry["proto"], registry["namespace"], registry["name"], registry["version"]))

# Claude marketplaces: the commit each one is at, and the plugins installed from them. Claude
# downloads some marketplaces (the official one) as an archive instead of cloning them; the
# archive's commit is in .gcs-sha. git -C on such a folder would read the repo around it.
plugins_dir = home + "/.claude/plugins"
for name, info in sorted(json.load(open(plugins_dir + "/known_marketplaces.json")).items()):
    source = info["source"].get("repo") or info["source"].get("url")
    location = info["installLocation"]
    toplevel = subprocess.run(["git", "-C", location, "rev-parse", "--show-toplevel"],
                              capture_output=True, text=True).stdout.strip()
    if toplevel and os.path.realpath(toplevel) == os.path.realpath(location):
        commit = subprocess.run(["git", "-C", location, "rev-parse", "HEAD"],
                                capture_output=True, text=True, check=True).stdout.strip()
    else:
        commit = open(location + "/.gcs-sha").read().strip()
    if not re.fullmatch(r"[0-9a-f]{40}", commit):
        sys.exit("marketplace %s: no commit found at %s" % (name, location))
    print("marketplace", name, source, commit)
for plugin, entries in sorted(json.load(open(plugins_dir + "/installed_plugins.json"))["plugins"].items()):
    print("plugin", plugin, entries[0]["version"], entries[0].get("gitCommitSha", "-"))

# Treesitter parsers; their revisions are pinned by the nvim-treesitter commit in lazy-lock.json.
for parser in sorted(glob.glob(home + "/.local/share/nvim/site/parser/*.so")):
    print("parser", os.path.basename(parser)[:-3])
PY

# A tool that is missing or prints no version leaves a "tool <name>" line; refuse a bad lock.
if awk '$1 == "tool" && NF < 3' "$lock" | grep -q .; then
  awk '$1 == "tool" && NF < 3' "$lock" >&2
  echo "ERROR: the lines above have no version; install the tool or fix version_of." >&2
  exit 1
fi
echo "Snapshot written to $out"
